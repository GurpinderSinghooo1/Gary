#!/usr/bin/env python3
"""
Builds the TV page (app/src/main/assets/web/home.html) from:
  design/concepts.html   - the design gallery (all 15 themes; also published as the preview page)
  web-src/tvhome.js      - bridge SDK (+ desktop mock)
  web-src/app.js         - TV runtime: data, remote navigation, menu, live extras
  web-src/tv.css         - TV-only styles

Run after editing any of those:   python3 tools/build_web.py
The design file stays the single source for how each theme looks.
"""
import pathlib, re, sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
src = (ROOT / "design/concepts.html").read_text(encoding="utf-8")

def between(text, start, end, inclusive=False):
    i = text.index(start)
    j = text.index(end, i + len(start))
    return text[i:j + len(end)] if inclusive else text[i + len(start):j]

fonts = re.search(r'<link rel="stylesheet" href="(https://fonts\.googleapis\.com[^"]+)">', src).group(1)
style = between(src, "<style>", "</style>")
screens = between(src, '<div class="tv" id="tv">', '</div></div>\n    <div class="stand">')
script = between(src, "<script>", "</script>")

# Keep the theme builders and the focus renderer; drop the gallery-only code (specs, tabs, keyboard).
cut = script.index("let cur=0;")
theme_js = script[:cut]

# Let the TV runtime swap in live data before any theme renders.
anchor = "const tile=(a,extra='')=>"
assert anchor in theme_js, "APPS/EXTRA anchor moved"
theme_js = theme_js.replace(anchor, "window.__applyData&&window.__applyData(APPS,EXTRA);\n" + anchor, 1)
picks_end = theme_js.index("];", theme_js.index("const PICKS=[")) + 2
theme_js = theme_js[:picks_end] + "\nwindow.__applyPicks&&window.__applyPicks(PICKS);" + theme_js[picks_end:]

tvhome = (ROOT / "web-src/tvhome.js").read_text(encoding="utf-8")
app = (ROOT / "web-src/app.js").read_text(encoding="utf-8")
tvcss = (ROOT / "web-src/tv.css").read_text(encoding="utf-8")

page = f"""<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>TV Home</title>
<!-- Generated by tools/build_web.py from design/concepts.html. Do not edit by hand. -->
<link rel="preconnect" href="https://fonts.googleapis.com">
<link rel="stylesheet" href="{fonts}">
<style>{style}
/* ---- TV overrides ---- */
{tvcss}</style>
</head>
<body>
<div class="tv" id="tv">{screens}</div>
<script>{tvhome}</script>
<script>
window.__buildThemes = function () {{
{theme_js}
return {{ screens: screens, state: state, hooks: hooks, render: render, APPS: APPS, EXTRA: EXTRA, PICKS: PICKS }};
}};
</script>
<script>{app}</script>
</body>
</html>
"""
out = ROOT / "app/src/main/assets/web/home.html"
out.parent.mkdir(parents=True, exist_ok=True)
out.write_text(page, encoding="utf-8")
print(f"wrote {out.relative_to(ROOT)} ({len(page)//1024} KB)")
